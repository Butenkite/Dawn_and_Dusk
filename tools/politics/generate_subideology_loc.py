"""Generate common/scripted_localisation/dnd_subideology.txt from the ideology file.

[dnd_GetSubideology] shows the ruling leader's ideology type ("African
Socialism") on the politics and diplomacy screens. Run this again whenever a
type is added to common/ideologies/dnd_ideologies.txt.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import MOD  # noqa: E402
src = (MOD / "common/ideologies/dnd_ideologies.txt").read_text(encoding="utf-8-sig")

types = []
for block in re.finditer(r"\btypes\s*=\s*\{(.*?)\n\t\t\}", src, re.S):
    types += re.findall(r"^\t\t\t([a-z_]+)\s*=", block.group(1), re.M)

out = [
    "# GENERATED by tools/politics/generate_subideology_loc.py - do not edit by hand.",
    "# Shows the ruling leader's ideology type (the sub-ideology).",
    "",
    "defined_text = {",
    "\tname = dnd_GetSubideology",
]
for t in types:
    out += [
        "\ttext = {",
        f"\t\ttrigger = {{ has_country_leader_ideology = {t} }}",
        f"\t\tlocalization_key = {t}",
        "\t}",
    ]
out += [
    "\ttext = {",
    "\t\tlocalization_key = DND_SUBIDEOLOGY_UNKNOWN",
    "\t}",
    "}",
    "",
]
(MOD / "common/scripted_localisation/dnd_subideology.txt").write_text(
    "\n".join(out), encoding="utf-8", newline="\n")
print(f"{len(types)} sub-ideologies written")
