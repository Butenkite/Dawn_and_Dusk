"""Generate party names for every country and every ideology group.

Vanilla names its parties per country for 1936 ("United", "GNP"...). Those
keys are overridden here, so every country shows either a real 2000-era
party from tools/data/parties.csv or a generic name for its group.

Usage (re-run after editing the CSV or the country list):
    python tools/politics/generate_party_names.py

Writes:
    localisation/english/replace/dnd_parties_l_english.yml
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import MOD, DATA  # noqa: E402

GENERIC = {
    "communism": ("Communist Party", "Communist Party"),
    "socialist": ("Socialist Party", "Socialist Party"),
    "social_democrat": ("Social Democrats", "Social Democratic Party"),
    "democratic": ("Liberal Party", "Liberal Party"),
    "conservative": ("Conservative Party", "Conservative Party"),
    "authoritarian_democrat": ("Ruling Party", "National Ruling Party"),
    "neutrality": ("Ruling Clique", "Ruling Clique"),
    "fascism": ("National Front", "National Front"),
}


def esc(s):
    return s.replace('"', '\\"')


def main():
    tags = [r["tag"] for r in csv.DictReader(open(DATA / "countries.csv", encoding="utf-8"))]
    custom = {}
    for r in csv.DictReader(open(DATA / "parties.csv", encoding="utf-8")):
        if r["group"] not in GENERIC:
            raise SystemExit(f"parties.csv: unknown group {r['group']}")
        custom[(r["tag"], r["group"])] = (r["short"], r["long"])
    lines = ["l_english:",
             " # GENERATED by tools/politics/generate_party_names.py - do not edit by hand.",
             " # Real parties come from tools/data/parties.csv; the rest are generic."]
    for tag in tags:
        for g, (short, long_) in GENERIC.items():
            s, l = custom.get((tag, g), (short, long_))
            lines.append(f' {tag}_{g}_party: "{esc(s)}"')
            lines.append(f' {tag}_{g}_party_long: "{esc(l)}"')
    out = MOD / "localisation/english/replace/dnd_parties_l_english.yml"
    out.parent.mkdir(parents=True, exist_ok=True)
    # Localisation: UTF-8 with BOM (see docs/CONVENTIONS.md).
    out.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    print(f"{len(tags)} countries, {len(custom)} real parties")


if __name__ == "__main__":
    main()
