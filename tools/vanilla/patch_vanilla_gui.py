"""Rebuild our modified copies of vanilla interface files from the current game.

Why: we override two vanilla screens (politics and diplomacy). When a HOI4
patch adds elements to those screens, the game's code looks for the new
elements by name, and an old copy without them crashes the game at the end
of loading. That is exactly what happened with 1.19.4. So never hand-edit
the copies: re-run this script after every HOI4 update, then test.

Each change is a small find-and-replace on the vanilla file. If a find string
is no longer in the new vanilla file, the script stops and says which one, so
nothing is silently skipped.

Usage:
    python tools/vanilla/patch_vanilla_gui.py "C:/Steam/steamapps/common/Hearts of Iron IV"

Writes:
    interface/countrypoliticsview.gui
    interface/countrydiplomacyview.gui
"""
