def patch(vanilla_file, out_file, header, edits):
    text = vanilla_file.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    for find, replace, count in edits:
        found = text.count(find)
        if found != count:
            sys.exit(f"{vanilla_file.name}: expected {count} of this, found {found}:\n{find}\n"
                     "Vanilla changed here; update the edit in tools/vanilla/patch_vanilla_gui.py.")
        text = text.replace(find, replace)
    # Script files: UTF-8 without BOM (see docs/CONVENTIONS.md).
    out_file.write_text(header + text, encoding="utf-8", newline="\r\n")
    print(f"wrote {out_file.relative_to(REPO)}")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    vanilla = Path(sys.argv[1]) / "interface"
    patch(vanilla / "countrypoliticsview.gui", MOD / "interface/countrypoliticsview.gui",
          POLITICS_HEADER, POLITICS_EDITS)
    patch(vanilla / "countrydiplomacyview.gui", MOD / "interface/countrydiplomacyview.gui",
          DIPLOMACY_HEADER, DIPLOMACY_EDITS)


if __name__ == "__main__":
    main()
