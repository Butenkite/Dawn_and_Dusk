"""Generate empty stand-ins for vanilla events, focuses and decisions.

Why: Dawn and Dusk removes vanilla's story content (events, focus trees,
decisions), but the generic vanilla systems we keep (laws, characters,
MIOs, AI, scripted effects...) still refer to that content by id.

  - A missing EVENT id crashes the game at the end of loading.
  - A missing FOCUS or DECISION id only logs an error, but there are
    thousands of them, which buries the errors that matter.

So every vanilla id is kept alive with an empty shell that can never fire,
be taken or be seen:

  - events:    hidden, triggered-only, no effects
  - focuses:   one hidden focus tree that no country ever gets
  - decisions: a hidden category whose decisions are never visible

No 1936 content survives, only the ids.

Usage (re-run after every HOI4 update):
    python tools/vanilla/generate_vanilla_stubs.py "C:/Steam/steamapps/common/Hearts of Iron IV"

Writes:
    events/dnd_vanilla_event_stubs.txt
    common/bop/dnd_vanilla_bop_stubs.txt
    common/ai_strategy/SOV.txt, ITA.txt (emptied)
    common/national_focus/dnd_vanilla_focus_stubs.txt
    common/decisions/categories/dnd_vanilla_decision_category_stubs.txt
    common/decisions/dnd_vanilla_decision_stubs.txt
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from paths import MOD  # noqa: E402
EVENT_TYPES = ("country_event", "news_event", "state_event",
               "unit_leader_event", "operative_leader_event")
HEADER = ("# GENERATED by tools/vanilla/generate_vanilla_stubs.py - do not edit by hand.\n"
          "# Empty stand-ins that keep vanilla ids alive. See the script.\n\n")


# --- a small Clausewitz parser ---------------------------------------------

def tokenize(text):
    for m in re.finditer(r'#[^\n]*|"[^"]*"|[{}]|[<>!]?=|[<>]|[^\s{}=<>!"#]+', text):
        t = m.group(0)
        if not t.startswith("#"):
            yield t


def parse(text):
    """Parse into a list of (key, op, value); value is a str or a nested list."""
    toks = list(tokenize(text))
    pos = 0

    def block():
        nonlocal pos
        items = []
        while pos < len(toks):
            t = toks[pos]
            if t == "}":
                pos += 1
                return items
            if t == "{":                      # anonymous block
                pos += 1
                items.append((None, None, block()))
                continue
            if pos + 1 < len(toks) and toks[pos + 1] in ("=", "<", ">", "<=", ">=", "!="):
                key, op = t, toks[pos + 1]
                pos += 2
                if pos < len(toks) and toks[pos] == "{":
                    pos += 1
                    items.append((key, op, block()))
                else:
                    items.append((key, op, toks[pos].strip('"') if pos < len(toks) else ""))
                    pos += 1
            else:                             # bare value in a list
                items.append((None, None, t.strip('"')))
                pos += 1
        return items

    return block()


def read(path):
    return path.read_text(encoding="utf-8-sig", errors="replace")


def first(items, key):
    for k, _, v in items:
        if k == key:
            return v
    return None


# --- events -----------------------------------------------------------------

def events(vanilla):
    namespaces, stubs, seen = [], [], set()
    for f in sorted((vanilla / "events").glob("*.txt")):
        for key, _, val in parse(read(f)):
            if key == "add_namespace" and isinstance(val, str):
                if val not in namespaces:
                    namespaces.append(val)
            elif key in EVENT_TYPES and isinstance(val, list):
                eid = first(val, "id")
                if eid and eid not in seen:
                    seen.add(eid)
                    stubs.append(f"{key} = {{ id = {eid} is_triggered_only = yes hidden = yes }}")
    text = HEADER + "\n".join(f"add_namespace = {ns}" for ns in namespaces) + "\n\n" + "\n".join(stubs) + "\n"
    return text, len(stubs)


# --- focuses ----------------------------------------------------------------

def focuses(vanilla):
    ids = []
    seen = set()
    trees = []
    for f in sorted((vanilla / "common/national_focus").glob("*.txt")):
        for key, _, val in parse(read(f)):
            blocks = []
            if key == "focus_tree" and isinstance(val, list):
                blocks = [v for k, _, v in val if k == "focus" and isinstance(v, list)]
                tid = first(val, "id")
                if tid and tid not in trees:
                    trees.append(tid)
            elif key in ("shared_focus", "joint_focus", "focus") and isinstance(val, list):
                blocks = [val]
            for b in blocks:
                fid = first(b, "id")
                if fid and fid not in seen:
                    seen.add(fid)
                    ids.append(fid)
    lines = [HEADER.rstrip("\n"),
             "# One hidden tree holding every vanilla focus id. No country ever gets",
             "# it (country factor 0, never loaded), so has_completed_focus on a",
             "# vanilla focus is simply always false instead of an error.",
             "",
             "focus_tree = {",
             "\tid = dnd_vanilla_focus_stubs",
             "\tcountry = { factor = 0 }",
             "\tdefault = no",
             "\treset_on_civilwar = no",
             ""]
    for i, fid in enumerate(ids):
        lines.append(f"\tfocus = {{ id = {fid} x = {i % 100} y = {i // 100} cost = 1 "
                     f"available = {{ always = no }} }}")
    lines += ["}", ""]
    # Vanilla tree ids too (load_focus_tree in kept scripts names them):
    # empty trees no country is ever given.
    lines += ["# Every vanilla focus tree id, each an empty tree no country gets.", ""]
    for tid in trees:
        lines += [f"focus_tree = {{ id = {tid} country = {{ factor = 0 }} default = no",
                  f"\tfocus = {{ id = dnd_stub_{tid} x = 0 y = 0 cost = 1 available = {{ always = no }} }}",
                  "}"]
    lines.append("")
    return "\n".join(lines), len(ids)


# --- decisions --------------------------------------------------------------

def decisions(vanilla):
    categories = []
    for f in sorted((vanilla / "common/decisions/categories").glob("*.txt")):
        for key, _, val in parse(read(f)):
            if key and isinstance(val, list) and key not in categories:
                categories.append(key)

    by_cat, seen = {}, set()
    for f in sorted((vanilla / "common/decisions").glob("*.txt")):
        for cat, _, val in parse(read(f)):
            if not cat or not isinstance(val, list):
                continue
            for did, _, body in val:
                if not did or not isinstance(body, list) or did in seen:
                    continue
                seen.add(did)
                extra = []
                # Keep the kind of decision, so mission and timed-decision
                # effects/triggers still validate.
                for k in ("days_mission_timeout", "days_remove"):
                    v = first(body, k)
                    if v is None:
                        continue
                    if not (isinstance(v, str) and re.fullmatch(r"-?\d+(\.\d+)?", v)):
                        v = "30"        # a variable or formula in vanilla; any number keeps the kind
                    extra.append(f"{k} = {v}")
                by_cat.setdefault(cat, []).append((did, extra))
                if cat not in categories:
                    categories.append(cat)

    cat_lines = [HEADER.rstrip("\n"),
                 "# Every vanilla decision category, hidden. See the script.", ""]
    for c in categories:
        cat_lines.append(f"{c} = {{ visible = {{ always = no }} allowed = {{ always = no }} }}")
    cat_lines.append("")

    dec_lines = [HEADER.rstrip("\n"),
                 "# Every vanilla decision id, never visible or available. See the script.", ""]
    n = 0
    for c in categories:
        if c not in by_cat:
            continue
        dec_lines.append(f"{c} = {{")
        for did, extra in by_cat[c]:
            e = (" " + " ".join(extra)) if extra else ""
            dec_lines.append(f"\t{did} = {{ allowed = {{ always = no }} visible = {{ always = no }} "
                             f"available = {{ always = no }}{e} }}")
            n += 1
        dec_lines.append("}")
    dec_lines.append("")
    return "\n".join(cat_lines), "\n".join(dec_lines), len(categories), n


# --- balances of power ------------------------------------------------------

def bops(vanilla):
    """Every vanilla balance of power, its sides and ranges kept by id, with no
    modifiers, decisions or effects. Kept scripts (characters, scripted
    effects) check and move them; with the stand-in they simply do nothing."""
    out = [HEADER.rstrip("\n"),
           "# Every vanilla balance of power, inert. No country ever has one.", ""]
    n = 0

    def rng(r, ind):
        rid = first(r, "id")
        return (f"{ind}range = {{ id = {rid} min = {first(r, 'min') or -1} "
                f"max = {first(r, 'max') or 1} modifier = {{ }} }}")
    for f in sorted((vanilla / "common/bop").glob("*.txt")):
        if f.name.startswith("_"):
            continue
        for key, _, val in parse(read(f)):
            if not key or not isinstance(val, list):
                continue
            out.append(f"{key} = {{")
            out.append(f"\tinitial_value = {first(val, 'initial_value') or 0}")
            out.append(f"\tleft_side = {first(val, 'left_side')}")
            out.append(f"\tright_side = {first(val, 'right_side')}")
            for k, _, v in val:
                if k == "range" and isinstance(v, list):
                    out.append(rng(v, "\t"))
                elif k == "side" and isinstance(v, list):
                    out.append("\tside = {")
                    out.append(f"\t\tid = {first(v, 'id')}")
                    if first(v, "icon"):
                        out.append(f"\t\ticon = {first(v, 'icon')}")
                    out += [rng(r, "\t\t") for k2, _, r in v if k2 == "range" and isinstance(r, list)]
                    out.append("\t}")
            out += ["}", ""]
            n += 1
    return "\n".join(out), n


# Vanilla files that are nothing but 1936 country content and only produce
# errors once that content is gone. Overridden with empty files.
EMPTY_OVERRIDES = [
    "common/ai_strategy/SOV.txt",
    "common/ai_strategy/ITA.txt",
]


def write(rel, text):
    p = MOD / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    # Script files: UTF-8 without BOM (see docs/CONVENTIONS.md).
    p.write_text(text, encoding="utf-8", newline="\r\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    vanilla = Path(sys.argv[1])
    text, n_ev = events(vanilla)
    write("events/dnd_vanilla_event_stubs.txt", text)
    text, n_fo = focuses(vanilla)
    write("common/national_focus/dnd_vanilla_focus_stubs.txt", text)
    cats, decs, n_cat, n_dec = decisions(vanilla)
    write("common/decisions/categories/dnd_vanilla_decision_category_stubs.txt", cats)
    write("common/decisions/dnd_vanilla_decision_stubs.txt", decs)
    text, n_bop = bops(vanilla)
    write("common/bop/dnd_vanilla_bop_stubs.txt", text)
    for rel in EMPTY_OVERRIDES:
        write(rel, HEADER + "# Emptied: 1936 country content, see EMPTY_OVERRIDES in the script.\n")
    print(f"{n_ev} event, {n_fo} focus, {n_cat} decision category, {n_dec} decision "
          f"and {n_bop} balance-of-power stubs; {len(EMPTY_OVERRIDES)} files emptied")


if __name__ == "__main__":
    main()
